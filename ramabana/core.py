"""The error type, the environment convention, and the one place that decides which model runs what.

## Errors and environment

A harness fails in two ways, and a person needs to be told them differently. `AgentError`
is a refusal -- something the harness will not do, which the user can act on. Anything else
is a bug, and should look like one.

## The model tables

`MODELS` maps a short name to the `(runtime, model_id)` pair that runs it. The short
names are the vocabulary the rest of the harness and the user share; the ids belong to
rishi (local) or fastllm (cloud). `JOBS` is the set of distinct jobs the policy can route
separately.

## Credentials

`auth_status` reports which credential sources fastllm could use. It reads status
metadata only: no function here returns, logs or stores a secret, and the Claude Code
login is probed by asking the `claude` binary, never by reading its credential file.

## Listing models

`available_models` is what a model picker renders. It lists the on-device models
unconditionally, adds llama.cpp only when that package is importable, and adds a vendor's
cloud catalog only when a credential for it exists -- so the list never offers a model the
process cannot actually run.

## Defaults and context windows

The default local model depends on the machine: MLX only exists on Apple silicon, so
elsewhere the litert gemma is the floor. `DEFAULT_POLICY` leaves `turn` unset -- that is the
user's choice -- and points the cheap, frequent jobs at a small local model.

## Resolving a model

A `ModelSpec` is a model after every question about it has been answered: which backend
runs it, what that backend should be handed, how big its context is, and anything worth
telling the user about how that was decided. Everything downstream takes a spec, never a
name, so the guessing happens once and in one place.

## Configurable models

`register_model` adds an alias for this process only. Persisting it is the host
application's business, since Ramabana does not own the user's configuration file. Passing
a Hugging Face URL is enough; rishi decides which runtime can serve it.

## Routing

`Routing` is job to model, and the only thing that decides what runs where. `turn` is
the model the user chose; every other job falls back to it when the policy has nothing to
say, so adding a job to `JOBS` cannot strand a caller without a model.

Docs: https://vedicreader.github.io/ramabana/core.html.md"""

