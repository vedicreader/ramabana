class ChoiceMenu:
    "A keyboard-selectable Teleprint overlay."
    def __init__(self, title, choices):
        self.title, self.choices, self.at = title, choices, 0

    def render(self):
        row = Text(f'{self.title}  ', style=f"bold {GRUVBOX['fg0']}")
        for i, (label, _) in enumerate(self.choices):
            row.append(f'{i + 1} {label}   ', style=GRUVBOX['fg0'] if i == self.at else GRUVBOX['gray'])
        row.append('esc cancel', style=GRUVBOX['gray'])
        return [row]

    def choose(self, key):
        if key == 'escape': return True, None
        if key in ('up', 'left'): self.at = (self.at - 1) % len(self.choices)
        elif key in ('down', 'right'): self.at = (self.at + 1) % len(self.choices)
        elif key.isdigit() and 0 < int(key) <= len(self.choices): return True, self.choices[int(key) - 1][1]
        elif key == 'enter': return True, self.choices[self.at][1]
        return False, None

def _refactor_question(text):
    "Whether a prompt should offer apply-vs-plan before it enters the transcript."
    p = str(text or '').lower()
    return any(w in p for w in ('refactor', 'restructure', 'rewrite this', 'clean up this code'))


async def run_turn(ui, prompt):
    """One turn, streamed into the transcript.

    The agent's `stream` is a blocking generator on the model's own thread, so the chunks
    come back over a queue rather than being awaited: the loop has to stay free the whole
    time, or an approval could never be answered and a tool call could never repaint.
    """
    loop, q = asyncio.get_running_loop(), asyncio.Queue()
    def pump():
        try:
            for chunk in ui.agent.stream_with(prompt, image=ui.image):
                loop.call_soon_threadsafe(q.put_nowait, chunk)
        except Exception as e: loop.call_soon_threadsafe(q.put_nowait, agent_err(e))
        finally:
            ui.image = None
            loop.call_soon_threadsafe(q.put_nowait, None)
    threading.Thread(target=pump, daemon=True).start()
    blk = None
    try:
        while (chunk := await q.get()) is not None: blk = ui.stream(blk, chunk)
    finally:
        ui.turn = None
        for p in ui.agent.problems: ui.say(Text(p), 'error')
        ui.agent.clear_problems()
        ui.paint()
    return blk

